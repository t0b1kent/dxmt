#!/usr/bin/env python3
"""MacRunner pso-cache (17.10.2026): chain version of the shader translator for the pipeline cache directory name.
usage: chain_version.py <output.h> <airconv source dir> [listed inputs...]
sha256 over the listed inputs plus every *.hpp/*.h/*.inc/*.metal/*.py and meson.build under the source dir (sorted by relative
path, path + contents), first 12 hex digits. The header is rewritten only when the value changes, so dependents do not rebuild."""
import hashlib, os, sys

def main():
    out, src = sys.argv[1], sys.argv[2]
    files = set(os.path.abspath(p) for p in sys.argv[3:])
    for root, _, names in os.walk(src):
        for n in names:
            if n.endswith(('.hpp', '.h', '.inc', '.metal', '.py')) or n == 'meson.build':
                files.add(os.path.abspath(os.path.join(root, n)))
    h = hashlib.sha256()
    for path in sorted(files, key=lambda p: os.path.relpath(p, src)):
        if os.path.abspath(out) == path:
            continue
        h.update(os.path.relpath(path, src).encode() + b'\0')
        with open(path, 'rb') as f:
            h.update(f.read())
        h.update(b'\0')
    version = h.hexdigest()[:12]
    # The unix winemetal (pipeline creation, archives, thunks) gets its own fingerprint: the layer mixes the value the loaded
    # winemetal.so reports into the cache directory key, so a PE/unix pair from different trees never shares a cache.
    wm = hashlib.sha256()
    wm_dir = os.path.join(os.path.dirname(src.rstrip('/')), 'winemetal')
    for root, _, names in os.walk(wm_dir):
        for n in sorted(names):
            if n.endswith(('.c', '.h', '.hpp', '.inc', '.m', '.mm')) or n == 'meson.build':
                path = os.path.join(root, n)
                wm.update(os.path.relpath(path, wm_dir).encode() + b'\0')
                with open(path, 'rb') as f:
                    wm.update(f.read())
                wm.update(b'\0')
    # The d3d12 layer names the functions and composes every pipeline description (pso-cache 17.10, 8a8f090 renamed the pixel
    # functions and the archives of the previous build stopped matching): its sources are part of the cache directory key too.
    ly = hashlib.sha256()
    ly_dir = os.path.join(os.path.dirname(src.rstrip('/')), 'd3d12')
    for root, _, names in os.walk(ly_dir):
        for n in sorted(names):
            if n.endswith(('.cpp', '.hpp', '.h', '.inc')) or n == 'meson.build':
                path = os.path.join(root, n)
                ly.update(os.path.relpath(path, ly_dir).encode() + b'\0')
                with open(path, 'rb') as f:
                    ly.update(f.read())
                ly.update(b'\0')
    text = ('// generated by chain_version.py; do not edit. sha256 of the airconv sources (and of src/winemetal, src/d3d12), first 12 hex digits.\n'
            '#pragma once\n#define AIRCONV_CHAIN_VERSION "%s"\n#define WINEMETAL_CHAIN_VERSION "%s"\n#define D3D12_LAYER_CHAIN_VERSION "%s"\n'
            % (version, wm.hexdigest()[:12], ly.hexdigest()[:12]))
    try:
        with open(out) as f:
            if f.read() == text:
                return 0
    except OSError:
        pass
    with open(out, 'w') as f:
        f.write(text)
    return 0

if __name__ == '__main__':
    sys.exit(main())
