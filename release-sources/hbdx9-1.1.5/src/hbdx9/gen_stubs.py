"""HBDX9: generate default (unimplemented) C++ method bodies for the D3D9 COM interfaces from mingw d3d9.h.

Every generated method logs its first use once ("HBDX9 unimpl: Iface::Method") and returns a neutral failure,
so a game shows exactly which API it needs next.  Real implementations override these in the shim classes."""
import re, sys

src, out = sys.argv[1], sys.argv[2]
text = open(src).read()
ifaces = ['IDirect3D9', 'IDirect3D9Ex', 'IDirect3DDevice9', 'IDirect3DDevice9Ex', 'IDirect3DSwapChain9',
          'IDirect3DSwapChain9Ex', 'IDirect3DResource9', 'IDirect3DSurface9', 'IDirect3DBaseTexture9',
          'IDirect3DTexture9', 'IDirect3DCubeTexture9', 'IDirect3DVolumeTexture9', 'IDirect3DVolume9', 'IDirect3DVertexBuffer9',
          'IDirect3DIndexBuffer9', 'IDirect3DVertexDeclaration9', 'IDirect3DVertexShader9', 'IDirect3DPixelShader9',
          'IDirect3DQuery9', 'IDirect3DStateBlock9']
blocks = {}
for m in re.finditer(r'DECLARE_INTERFACE_IID_\((\w+),(\w+),"[^"]+"\)\s*\{(.*?)\n\};', text, re.S):
    blocks[m.group(1)] = (m.group(2), m.group(3))
own = {}
for name in ifaces:
    parent, body = blocks[name]
    decls = re.sub(r'/\*.*?\*/', '', body, flags=re.S)
    decls = ' '.join(decls.split())
    methods = []
    for d in re.finditer(r'STDMETHOD(?:_\(\s*([\w\s\*]+?)\s*,\s*(\w+)\s*\)|\((\w+)\))\((THIS_?)\s*(.*?)\)\s*PURE;', decls):
        ret = (d.group(1) or 'HRESULT').strip()
        mname = d.group(2) or d.group(3)
        args = d.group(5).strip() if d.group(4) == 'THIS_' else ''
        methods.append((ret, mname, args))
    own[name] = (parent, methods)

def default(ret):
    if ret == 'HRESULT': return 'D3DERR_INVALIDCALL'
    if ret == 'void': return None
    if ret in ('float', 'FLOAT'): return '0.0f'
    return f'({ret})0'

lines = ['/* generated by gen_stubs.py from mingw d3d9.h — do not edit */', '#pragma once', '#include "hbdx9_common.hpp"', '']
for name in ifaces:
    parent, methods = own[name]
    chain = []
    p = name
    while p in own:
        chain.insert(0, p); p = own[p][0]
    lines.append(f'template <typename Base> class Hbdx9Stub_{name} : public Base {{')
    lines.append('public:')
    seen = set()
    for iface in chain:
        for ret, mname, args in own[iface][1]:
            if mname in ('QueryInterface', 'AddRef', 'Release') or mname in seen: continue
            seen.add(mname)
            argnames = []
            for a in [x.strip() for x in args.split(',') if x.strip()]:
                toks = a.replace('*', ' * ').split()
                nm = re.findall(r'(\w+)\s*(?:\[\w*\])?$', a) if len(toks) > 1 and toks[-1] != '*' else []
                argnames.append(nm[0] if nm else '')
            unused = ''.join(f' (void){n};' for n in argnames if n)
            d = default(ret)
            body = f'{unused} hbdx9_unimpl("{iface}::{mname}");' + (f' return {d};' if d is not None else '')
            lines.append(f'  {ret} STDMETHODCALLTYPE {mname}({args}) override {{{body} }}')
    lines.append('};')
    lines.append('')
open(out, 'w').write('\n'.join(lines) + '\n')
print('methods:', {k: len(v[1]) for k, v in own.items()})
